import SwiftUI

/// Кнопка «Готово» над клавиатурой. У цифровой клавиатуры нет клавиши Return,
/// и без этой кнопки её нечем убрать: она закрывает форму, а до кнопки
/// «Сохранить» не добраться.
///
/// `dismiss` снимает фокус с поля, которое сейчас в фокусе. Фокус должен быть
/// заведён на все поля формы, а не только на числовые: иначе кнопка окажется
/// на экране, а нажатие ничего не сделает.
extension View {
    func keyboardDone(_ dismiss: @escaping () -> Void) -> some View {
        toolbar {
            ToolbarItemGroup(placement: .keyboard) {
                Spacer()
                Button("Готово", action: dismiss)
            }
        }
    }
}
