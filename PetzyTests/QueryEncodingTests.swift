import Foundation
@testable import Petzy
import Testing

/// Значения, которые уходят в строке запроса, должны дойти до сервера ровно
/// теми, что человек ввёл. Стандартный набор разрешённых знаков оставляет `&`
/// и `+` как есть, а в строке запроса они значат разделитель и пробел.
@Suite("Строка запроса")
struct QueryEncodingTests {
    /// Амперсанд разделяет параметры. Без экранирования поиск по «а&б» искал
    /// бы «а», а второе слово ушло бы в отдельный параметр, которого сервер
    /// не ждёт.
    @Test("Амперсанд не разрывает параметры")
    func ampersandIsEscaped() {
        #expect(AppModel.query("a&b") == "a%26b")
    }

    /// Плюс сервер читает как пробел. Из-за этого часовой пояс «GMT+05:00»
    /// приходил как «GMT 05:00», а токен сброса пароля с плюсом не проходил
    /// проверку: человек открывал ссылку из письма и получал отказ.
    @Test("Плюс не превращается в пробел")
    func plusIsEscaped() {
        #expect(AppModel.query("GMT+05:00") == "GMT%2B05%3A00")
        #expect(AppModel.query("a+b") == "a%2Bb")
    }

    /// Обычные значения не должны пострадать: идентификаторы, ключи типов,
    /// даты и имена питомцев.
    @Test("Обычные значения остаются читаемыми")
    func ordinaryValuesStayTheSame() {
        #expect(AppModel.query("demo") == "demo")
        #expect(AppModel.query("2026-10-19") == "2026-10-19")
        #expect(AppModel.query("weight") == "weight")
        #expect(AppModel.query("6ad555dc246d9b37ad852876") == "6ad555dc246d9b37ad852876")
    }

    /// Кириллица и пробел уходят закодированными: сервер должен получить
    /// «Анна Иванова», а не мусор.
    @Test("Кириллица и пробел уходят закодированными")
    func cyrillicAndSpaceAreEncoded() {
        #expect(AppModel
            .query("Анна Иванова") == "%D0%90%D0%BD%D0%BD%D0%B0%20%D0%98%D0%B2%D0%B0%D0%BD%D0%BE%D0%B2%D0%B0")
    }
}
